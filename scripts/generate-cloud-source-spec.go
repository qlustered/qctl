//go:build ignore

// generate-cloud-source-spec.go emits internal/cloud_sources/spec.gen.go: the
// fields of a CloudSource manifest's spec, derived from
// api.DataSourceModelPatchRequestSchema.
//
// Every field of that schema lands in the manifest except the ones in excluded
// below. A field whose key ends in _override goes to SettingsOverrides under the
// key without the suffix; every other one goes to CloudSourceFields under its
// own key. Each is a pointer with yaml and json tags.
//
// Usage: go run scripts/generate-cloud-source-spec.go > internal/cloud_sources/spec.gen.go
package main

import (
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"

	"github.com/qlustered/qctl/internal/api"
	"github.com/qlustered/qctl/internal/pkg/codegen"
)

const overrideSuffix = "_override"

// The category of an excluded key, in the order the emitted CloudSourceFields
// doc comment lists them.
const (
	status   = "status"
	metadata = "metadata.name"
	identity = "declared on CloudSourceSpec"
	dropped  = "not source configuration"
)

var categories = []string{status, metadata, identity, dropped}

// excluded is every key of api.DataSourceModelPatchRequestSchema that is not a
// generated manifest field. A key here that is no longer on the schema fails the
// generator.
var excluded = map[string]string{
	"id":                   status,
	"version_id":           status,
	"state":                status,
	"internal_id":          status,
	"delta_applied_cursor": status,

	"name": metadata,

	"dataset_id":        identity,
	"data_source_type":  identity,
	"settings_model_id": identity,

	"redirect_post_submit_to":          dropped,
	"excluded_row_signatures_override": dropped,
}

// field is one emitted struct field: the manifest key, the Go name and the
// rendered type.
type field struct {
	key    string
	name   string
	goType string
}

func main() {
	rt := reflect.TypeOf(api.DataSourceModelPatchRequestSchema{})

	var imports codegen.Imports
	var fields, overrides []field
	seen := map[string]bool{}
	for i := 0; i < rt.NumField(); i++ {
		f := rt.Field(i)
		key := codegen.JSONKey(f)
		if key == "" || key == "-" {
			fail("api.DataSourceModelPatchRequestSchema.%s has no usable json tag", f.Name)
		}
		seen[key] = true
		if _, skip := excluded[key]; skip {
			continue
		}
		gt, err := imports.GoType(f.Type)
		if err != nil {
			fail("api.DataSourceModelPatchRequestSchema.%s (%s): %v", f.Name, key, err)
		}
		gt = codegen.PointerTo(gt)

		name, isOverride := strings.CutSuffix(key, overrideSuffix)
		if !isOverride {
			fields = append(fields, field{key: key, name: f.Name, goType: gt})
			continue
		}
		goName, ok := strings.CutSuffix(f.Name, "Override")
		if !ok || goName == "" {
			fail("api.DataSourceModelPatchRequestSchema.%s carries %s but its Go name does not end in Override", f.Name, key)
		}
		overrides = append(overrides, field{key: name, name: goName, goType: gt})
	}

	for key, where := range excluded {
		if !seen[key] {
			fail("%q is on the exclusion list (%s) but no longer on api.DataSourceModelPatchRequestSchema; delete the entry", key, where)
		}
	}
	if len(fields) == 0 || len(overrides) == 0 {
		fail("api.DataSourceModelPatchRequestSchema produced %d fields and %d overrides; expected both", len(fields), len(overrides))
	}

	byKey := func(s []field) {
		sort.Slice(s, func(i, j int) bool { return s[i].key < s[j].key })
	}
	byKey(fields)
	byKey(overrides)

	var b strings.Builder
	b.WriteString("// Code generated by scripts/generate-cloud-source-spec.go. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: make generate-client\n\n")
	b.WriteString("package cloud_sources\n\n")
	b.WriteString(imports.Decl())

	b.WriteString("// CloudSourceFields is the part of a CloudSource manifest's spec that maps one\n")
	b.WriteString("// to one onto api.DataSourceModelPatchRequestSchema: every field of it except\n")
	b.WriteString("// the ones below, each a pointer.\n//\n")
	for _, where := range categories {
		var keys []string
		for key, w := range excluded {
			if w == where {
				keys = append(keys, key)
			}
		}
		sort.Strings(keys)
		fmt.Fprintf(&b, "//   - %s: %s.\n", strings.Join(keys, ", "), where)
	}
	b.WriteString("//   - every other *_override: SettingsOverrides.\n")
	b.WriteString("type CloudSourceFields struct {\n")
	writeFields(&b, fields)
	b.WriteString("}\n\n")

	var excludedOverrides []string
	for key := range excluded {
		if strings.HasSuffix(key, overrideSuffix) {
			excludedOverrides = append(excludedOverrides, key)
		}
	}
	sort.Strings(excludedOverrides)
	b.WriteString("// SettingsOverrides is a CloudSource manifest's spec.settings_overrides: every\n")
	b.WriteString("// *_override field of api.DataSourceModelPatchRequestSchema")
	if len(excludedOverrides) > 0 {
		fmt.Fprintf(&b, " except\n// %s", strings.Join(excludedOverrides, ", "))
	}
	b.WriteString(", keyed without the suffix.\n")
	b.WriteString("type SettingsOverrides struct {\n")
	writeFields(&b, overrides)
	b.WriteString("}\n")

	fmt.Print(b.String())
}

func writeFields(b *strings.Builder, fields []field) {
	for _, f := range fields {
		fmt.Fprintf(b, "\t%s %s `yaml:%q json:%q`\n", f.name, f.goType, f.key+",omitempty", f.key+",omitempty")
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "generate-cloud-source-spec: "+format+"\n", args...)
	os.Exit(1)
}
