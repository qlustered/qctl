// TestSettingsModelMirrorsTheWireSchema is the tripwire that lets
// settings_model.gen.go be trusted without regenerating it.
//
// scripts/generate-settings-model.go derives the manifest from
// api.SettingsSchema, and because it needs no downloaded spec the derivation is
// reproducible here: for every key the manifest carries, this asserts the field
// is exactly what the generator would have emitted -- same Go name, same type
// with one pointer added, both tags spelled with the wire key and omitempty.
//
// The case it exists for is the one nothing else can see: a regen moves a type
// on api.SettingsSchema and the committed settings_model.gen.go still has the
// old one. The manifest stays SELF-consistent there, so every test literal and
// all three converters still compile -- the converters are generic JSON and
// never name a field -- and the only symptom is a settings key that silently
// stops decoding. Verified by mutation: retyping max_boundary_element_length to
// *string while the package still compiles fails here and nowhere else.
//
// Editing the generated file by hand usually fails to COMPILE first, since the
// test literals in this package name all 43 fields. That is a fine outcome and
// not what these assertions are for.
//
// TestSettingsModelCoversEverySettingsKey is the other half: that one checks the
// KEY SET matches, this one checks each field's SHAPE. Neither implies the
// other.
func TestSettingsModelMirrorsTheWireSchema(t *testing.T) {
	wire := map[string]reflect.StructField{}
	wt := reflect.TypeOf(api.SettingsSchema{})
	for i := 0; i < wt.NumField(); i++ {
		f := wt.Field(i)
		wire[tagKey(f.Tag.Get("json"), f.Name)] = f
	}

	mt := reflect.TypeOf(SettingsModel{})
	for i := 0; i < mt.NumField(); i++ {
		f := mt.Field(i)
		key := tagKey(f.Tag.Get("yaml"), f.Name)

		src, ok := wire[key]
		if !ok {
			// TestSettingsModelCoversEverySettingsKey reports this one with the
			// consequence spelled out; nothing to compare shapes against here.
			continue
		}

		if f.Name != src.Name {
			t.Errorf("%s is api.SettingsSchema.%s but SettingsModel.%s; the generator takes the Go name from the wire type, so a rename here means the file was hand-edited", key, src.Name, f.Name)
		}

		want := pointerTo(src.Type)
		if f.Type != want {
			t.Errorf("%s is %s on SettingsModel, want %s (api.SettingsSchema has %s)", key, f.Type, want, src.Type)
		}

		if f.Type.Kind() != reflect.Pointer {
			t.Errorf("%s is %s, which is not a pointer: the manifest could not tell \"absent\" from \"written as a zero value\", and a {} or [] clear would be dropped on marshal", key, f.Type)
		}

		for _, tag := range []string{"yaml", "json"} {
			got := f.Tag.Get(tag)
			if want := key + ",omitempty"; got != want {
				t.Errorf("%s has %s:%q, want %q -- without omitempty every unset key is emitted as null, and get table -o yaml prints all 43 of them", key, tag, got, want)
			}
		}
	}

	// Alphabetical by key, which is the order the generator emits and the order
	// a reader of `get table -o yaml` expects to be able to scan.
	var keys []string
	for i := 0; i < mt.NumField(); i++ {
		keys = append(keys, tagKey(mt.Field(i).Tag.Get("yaml"), mt.Field(i).Name))
	}
	for i := 1; i < len(keys); i++ {
		if keys[i-1] > keys[i] {
			t.Errorf("settings_model.gen.go is out of order at %s / %s; the generator sorts by key", keys[i-1], keys[i])
		}
	}
}

// pointerTo mirrors the generator's rule: api.SettingsSchema gives a nullable
// column as *[]string and a required one as []string for the same manifest
// need, so the manifest adds a pointer to whatever is not already one.
func pointerTo(t reflect.Type) reflect.Type {
	if t.Kind() == reflect.Pointer {
		return t
	}
	return reflect.PointerTo(t)
}

// TestSettingsModelGenFileIsGenerated keeps the DO NOT EDIT banner honest. The
// file is the only place the manifest's field list exists, so an editor who
// misses the banner and adds a field by hand gets it silently reverted by the
// next `make generate-client` -- with the manifest key it named quietly
// disappearing from every table.
func TestSettingsModelGenFileIsGenerated(t *testing.T) {
	const path = "settings_model.gen.go"
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	src := string(raw)

	for _, want := range []string{
		"// Code generated by scripts/generate-settings-model.go. DO NOT EDIT.",
		"// Regenerate with: make generate-client",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("%s is missing %q; without it nothing tells a reader the file is machine-written", path, want)
		}
	}
}
